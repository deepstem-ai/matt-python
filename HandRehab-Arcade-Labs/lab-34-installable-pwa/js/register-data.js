// ระดับความปวด 0-10 (Numeric Rating Scale ที่นักกายภาพใช้กันทั่วไป)
export function painText(v) {
  v = Number(v);
  if (v === 0) return '😀 ไม่ปวดเลย';
  if (v <= 3) return '🙂 ปวดเล็กน้อย ทำกิจกรรมได้ตามปกติ';
  if (v <= 6) return '😐 ปวดปานกลาง รบกวนการทำกิจกรรมบ้าง';
  if (v <= 9) return '😣 ปวดมาก ควรปรึกษานักกายภาพก่อนฝึก';
  return '😭 ปวดมากที่สุด — ยังไม่ควรฝึก ควรพบแพทย์';
}


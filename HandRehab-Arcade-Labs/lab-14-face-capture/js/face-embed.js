const d3 = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);

// อัตราส่วนของหน้ามาตรฐาน (คำนวณครั้งเดียวตอนโหลดไฟล์)
const REF = (() => {
  const iod = d3(CANON[33], CANON[263]);
  return PAIRS.map(([i, j]) => d3(CANON[i], CANON[j]) / iod);
})();

export const EMBED_SIZE = PAIRS.length; // 50 ตัวเลข

// makeEmbedding(landmarks, {width, height})
//  landmarks = จุด 478 จุดจาก Face Landmarker แต่ละจุด {x, y, z} (x, y เป็นสัดส่วน 0-1 ของภาพ)
//  width/height = ขนาดภาพจริง ใช้แก้ให้ x กับ y มีหน่วยเดียวกัน (ภาพ 16:9 ไม่ใช่สี่เหลี่ยมจัตุรัส)
//  z ของ MediaPipe ใช้สเกลประมาณเดียวกับ x จึงคูณด้วย width เหมือน x
//  คืน Float32Array ยาว 50 หรือ null ถ้าข้อมูลไม่พอ
export function makeEmbedding(landmarks, { width = 1, height = 1 } = {}) {
  if (!landmarks || landmarks.length < 468) return null;
  const P = (i) => { const p = landmarks[i]; return [p.x * width, p.y * height, (p.z || 0) * width]; };
  const iod = d3(P(EYE_OUTER[0]), P(EYE_OUTER[1]));
  if (!(iod > 1e-9)) return null; // หางตาทับกัน = ข้อมูลเสีย
  const out = new Float32Array(PAIRS.length);
  let mean = 0;
  PAIRS.forEach(([i, j], k) => {
    // log(อัตราส่วนของเรา / อัตราส่วนหน้ามาตรฐาน): 0 = เหมือนหน้ามาตรฐานพอดี, บวก = ยาวกว่า, ลบ = สั้นกว่า
    out[k] = Math.log(d3(P(i), P(j)) / iod / REF[k]);
    mean += out[k];
  });
  mean /= PAIRS.length;
  for (let k = 0; k < out.length; k++) out[k] -= mean; // ลบค่าเฉลี่ย (ข้อ 5 ด้านบน)
  return out;
}

// cosineSimilarity(a, b) — ความเหมือนระหว่างชุดตัวเลขสองชุด 0 ถึง 1
//  = cos ของมุมระหว่างลูกศรสองดอก (ชี้ทางเดียวกัน = 1, ตั้งฉาก = 0)
//  ค่าติดลบ (ชี้สวนทาง = ต่างกันแน่นอน) ปัดเป็น 0 เพื่อให้อ่านง่ายเป็น 0..1
export function cosineSimilarity(a, b) {
  if (!a || !b || a.length !== b.length || a.length === 0) return 0;
  let dot = 0, na = 0, nb = 0;
  for (let i = 0; i < a.length; i++) { dot += a[i] * b[i]; na += a[i] * a[i]; nb += b[i] * b[i]; }
  if (na === 0 || nb === 0) return 0;
  return Math.max(0, Math.min(1, dot / Math.sqrt(na * nb)));
}

// ค่าเฉลี่ยของหลาย embedding (ใช้รวมหลายเฟรมให้นิ่งขึ้น)
export function averageEmbedding(list) {
  const ok = list.filter(Boolean);
  if (!ok.length) return null;
  const out = new Float32Array(ok[0].length);
  ok.forEach((e) => e.forEach((v, i) => { out[i] += v / ok.length; }));
  return out;
}

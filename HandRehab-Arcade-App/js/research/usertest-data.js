// ---------- ข้อมูลตัวอย่าง: ผู้เข้าร่วมสมมติ 5 คน (ติดป้าย demo ชัดเจน ห้ามใช้ในรายงาน) ----------
// สุ่มแบบมีเมล็ด (seed) ให้ได้ค่าเดิมทุกครั้ง
function seeded(seed) {
  let s = seed;
  return () => { s = (s * 16807) % 2147483647; return (s - 1) / 2147483646; };
}
export function demoSurveys(now = Date.now()) {
  const rnd = seeded(42);
  const bias = [4.4, 4.0, 3.6, 4.6, 4.4, 3.2, 3.8, 3.4, 3.6, 3.0]; // แนวโน้มแต่ละข้อ
  const quotes = ['ปุ่มใหญ่ดี แต่ไม่รู้ว่าต้องกะพริบตา', 'สนุกเหมือนเล่นเกมกับหลาน', 'มือล้านิดหน่อยตอนท้าย', 'กลัวรูปหน้าหลุดไปที่อื่น', 'อยากให้มีเสียงบอกว่าต้องทำอะไร'];
  return quotes.map((c, i) => {
    const answers = {};
    QUESTIONS.forEach((q, k) => { answers[q.id] = Math.max(1, Math.min(5, Math.round(bias[k] + (rnd() - 0.5) * 2.2))); });
    return { id: 'demo-s' + (i + 1), userId: 'DEMO-P0' + (i + 1), participant: 'DEMO-P0' + (i + 1), createdAt: now - (5 - i) * 3600e3, answers, comment: c, demo: true };
  });
}
export function demoTaskRecords(now = Date.now()) {
  const rnd = seeded(7);
  return [1, 2, 3, 4, 5].map((n) => ({
    key: 'usertest-demo-P0' + n,
    value: {
      participant: 'DEMO-P0' + n, facilitator: 'DEMO', startedAt: now - (6 - n) * 3600e3, demo: true,
      tasks: TASKS.map((t) => {
        const r = rnd();
        const outcome = r < 0.62 ? 'alone' : r < 0.87 ? 'help' : 'fail';
        return { id: t.id, outcome, seconds: Math.round(t.maxSec * (0.25 + rnd() * 0.7)), note: '' };
      }),
    },
  }));
}

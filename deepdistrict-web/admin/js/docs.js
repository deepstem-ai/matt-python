      '<button class="btn" data-doc="print">' + L("Print", "พิมพ์") + "</button>" + (A.isStaff() ? '<button class="btn" data-doc="email">✉ ' + L("Email", "ส่งอีเมล") + "</button>" : "") + "</div>";

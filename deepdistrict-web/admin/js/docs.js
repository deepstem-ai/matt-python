  /* ------------------------------------------------------------ exporters */
  A.canvasOf = function (el) {
    if (!window.html2canvas) return Promise.reject(new Error(L("Export library missing (admin/vendor).", "ไม่พบไลบรารีสำหรับส่งออก (admin/vendor)")));
    document.body.classList.add("is-exporting");
    return document.fonts.ready.then(function () {
      return html2canvas(el, { scale: 2, backgroundColor: "#ffffff", useCORS: true, logging: false,
        ignoreElements: function (n) { return (n.classList && n.classList.contains("no-export")) || (location.protocol === "file:" && (n.tagName === "IMG" || n.tagName === "image")); } });
    }).finally(function () { document.body.classList.remove("is-exporting"); });
  };
  A.pngBlob = function (el) { return A.canvasOf(el).then(function (c) { return new Promise(function (res) { c.toBlob(res, "image/png"); }); }); };
  A.pdfBlob = function (el) {
    return A.canvasOf(el).then(function (c) {
      var wide = el.classList.contains("report--wide");
      var pdf = new window.jspdf.jsPDF({ orientation: wide ? "landscape" : "portrait", unit: "mm", format: "a4" });
      var pw = pdf.internal.pageSize.getWidth(), ph = pdf.internal.pageSize.getHeight(), m = 10;
      var iw = pw - m * 2, scale = iw / c.width, pageH = Math.floor((ph - m * 2) / scale);
      for (var y = 0, page = 0; y < c.height; y += pageH, page++) {
        var h = Math.min(pageH, c.height - y), part = document.createElement("canvas");
        part.width = c.width; part.height = h;
        part.getContext("2d").drawImage(c, 0, y, c.width, h, 0, 0, c.width, h);
        if (page) pdf.addPage();
        pdf.addImage(part.toDataURL("image/jpeg", 0.92), "JPEG", m, m, iw, h * scale);
      }
      return pdf.output("blob");
    });
  };
  function b64(blob) { return new Promise(function (res) { var r = new FileReader(); r.onload = function () { res(String(r.result).split(",")[1]); }; r.readAsDataURL(blob); }); }
  function fail(e) { if (e) A.toast(L("Export failed: ", "ส่งออกไม่สำเร็จ: ") + (e.message || e), "err"); }

  /* Email a document. Uses the server's SMTP settings; otherwise shares or downloads + opens the mail app. */
  A.emailDoc = function (el, base, opts) {
    opts = opts || {};
    A.form({
      title: L("Send by email", "ส่งทางอีเมล"),
      submit: L("Send", "ส่ง"),
      fields: [
        { name: "to", label: L("To (comma-separated)", "ถึง (คั่นด้วยเครื่องหมายจุลภาค)"), value: (opts.to || []).filter(Boolean).join(", "), required: true, full: true },
        { name: "subject", label: L("Subject", "หัวเรื่อง"), value: opts.subject || base, required: true, full: true },
        { name: "text", label: L("Message", "ข้อความ"), type: "textarea", full: true, value: opts.text || L("Dear parent / learner,\n\nPlease find the document attached.\n\nBest regards,\n", "เรียน ผู้ปกครอง / ผู้เรียน\n\nส่งเอกสารตามไฟล์แนบ\n\nขอแสดงความนับถือ\n") + A.db.org.name },
        { name: "format", label: L("Attach as", "แนบเป็น"), type: "select", value: "pdf", options: [["pdf", "PDF"], ["png", L("Image (PNG)", "รูปภาพ (PNG)")], ["both", "PDF + PNG"]] }
      ],
      validate: function (v) { if (!v.to.split(",").some(function (t) { return /@/.test(t); })) return L("Enter at least one email address.", "กรุณาใส่อีเมลอย่างน้อย 1 รายการ"); },
      onSave: function (v) {
        var to = v.to.split(",").map(function (t) { return t.trim(); }).filter(Boolean);
        var jobs = [];
        if (v.format !== "png") jobs.push(A.pdfBlob(el).then(function (b) { return { filename: base + ".pdf", mime: "application/pdf", blob: b }; }));
        if (v.format !== "pdf") jobs.push(A.pngBlob(el).then(function (b) { return { filename: base + ".png", mime: "image/png", blob: b }; }));
        A.toast(L("Preparing…", "กำลังเตรียมไฟล์…"));
        return Promise.all(jobs).then(function (files) {
          return A.api("GET", "smtp").then(function (cfg) {
            if (!cfg.configured) return shareFallback(files, to, v);
            return Promise.all(files.map(function (f) { return b64(f.blob).then(function (d) { return { filename: f.filename, mime: f.mime, data: d }; }); }))
              .then(function (att) { return A.api("POST", "email", { to: to, subject: v.subject, text: v.text, attachments: att }); })
              .then(function () { A.toast(L("Email sent to ", "ส่งอีเมลถึง ") + to.join(", ")); });
          });
        }).catch(function (e) { A.toast(L("Not sent: ", "ส่งไม่สำเร็จ: ") + e.message, "err"); return false; });
      }
    });
  };
  function shareFallback(files, to, v) {
    var fl = files.map(function (f) { return new File([f.blob], f.filename, { type: f.mime }); });
    if (navigator.canShare && navigator.canShare({ files: fl })) {
      return navigator.share({ files: fl, title: v.subject, text: v.text }).catch(function () {});
    }
    files.forEach(function (f) { A.download(f.filename, f.blob); });
    location.href = "mailto:" + encodeURIComponent(to.join(",")) + "?subject=" + encodeURIComponent(v.subject) + "&body=" + encodeURIComponent(v.text + "\n\n(" + L("attach: ", "แนบไฟล์: ") + files.map(function (f) { return f.filename; }).join(", ") + ")");
    A.toast(L("Email is not set up on the server, so the file was downloaded and your mail app opened — please attach it.", "ยังไม่ได้ตั้งค่าอีเมลบนเซิร์ฟเวอร์ ระบบจึงดาวน์โหลดไฟล์และเปิดแอปอีเมลให้ กรุณาแนบไฟล์ก่อนส่ง"), "warn");
  }
  A.docExport = function (kind, el, base, emailOpts) {
    el = el || $("#report");
    if (!el) return;
    if (kind === "pdf") return A.pdfBlob(el).then(function (b) { A.download(base + ".pdf", b); A.logAct("Exported " + base + ".pdf"); A.save(); }).catch(fail);
    if (kind === "png") return A.pngBlob(el).then(function (b) { A.download(base + ".png", b); }).catch(fail);
    if (kind === "print") return window.print();
    if (kind === "email") return A.emailDoc(el, base, emailOpts);
  };

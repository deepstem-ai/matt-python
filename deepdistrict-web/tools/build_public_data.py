"""Build the website's offline copies of the starter news and the free sample tests.

    python3 tools/build_public_data.py

Writes
  assets/data/news.js   window.DD_NEWS  — starter news (server/blog_posts/*.json), shown on the home-page
                                          slider and the blog when the site runs without the server
  assets/data/tests.js  window.DD_TESTS — the 12 ready-made sets (server/exam_sets/*.json) with a few
                                          sample questions each, for the public "Free practice tests" page
Run it again after editing either folder.
"""
import json
import os
import sys
from datetime import datetime, timedelta, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "server"))
import blog  # noqa: E402
import blog_seed  # noqa: E402
import ready_sets  # noqa: E402

HEAD = "/* Generated by tools/build_public_data.py — do not edit by hand. */\n"


def news():
    cats = {c["id"]: c for c in blog.DEFAULT_SETTINGS["categories"]}
    base = datetime(2026, 10, 30, 3, 0, tzinfo=timezone.utc)
    items = []
    for x in blog_seed.posts():
        c = cats.get(x["category"]) or blog.DEFAULT_SETTINGS["categories"][0]
        items.append({"id": "s-" + x["slug"][:20], "slug": x["slug"], "branch": c["branch"], "category": c["id"], "categoryName": c["name"],
                      "title": x["title"], "summary": x["summary"], "body": x["body"], "tags": x.get("tags", []), "sources": x.get("sources", []),
                      "cover": blog_seed._cover(*x["cover"]), "coverKind": "drawing", "coverCredit": None,
                      "publishedAt": (base - timedelta(days=int(x.get("days") or 0))).isoformat(), "aiLabel": None})
    items.sort(key=lambda p: p["publishedAt"], reverse=True)
    return {"items": items, "branches": blog.BRANCHES, "categories": blog.DEFAULT_SETTINGS["categories"], "static": True}


def spread(lst, n):
    if len(lst) <= n:
        return list(lst)
    step = len(lst) / n
    return [lst[int(i * step)] for i in range(n)]


def sample_items(d):
    its = d["items"]
    if d["exam"] == "ielts":
        r = [x for x in its if x["kind"] == "ielts-r"][0]
        w = [x for x in its if x["kind"] == "ielts-w"]
        return {"reading": r, "writing": w}
    if d["exam"] == "sat":
        return {"questions": spread(its, 6)}
    by = {}
    for x in its:
        by.setdefault(x["subject"], []).append(x)
    out = []
    for sub, lst in by.items():
        out += spread(lst, 3 if sub in ("math", "sci", "eng") else 2)
    return {"questions": out}


def tests():
    out = []
    for d in ready_sets.files():
        kinds = {}
        for x in d["items"]:
            kinds[x["kind"]] = kinds.get(x["kind"], 0) + 1
        out.append({"exam": d["exam"], "set": d.get("set"), "title": d.get("title"), "note": d.get("note"), "minutes": d.get("minutes"),
                    "kinds": kinds, "sample": sample_items(d)})
    return out


def write(name, var, data):
    path = os.path.join(ROOT, "assets", "data", name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEAD + "window." + var + " = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{name}: {os.path.getsize(path) // 1024} KB")


if __name__ == "__main__":
    write("news.js", "DD_NEWS", news())
    write("tests.js", "DD_TESTS", tests())

#!/usr/bin/env python3
"""Generate docs/CURRICULUM.md (bilingual) from the site's data files.

Reads assets/data/content.js, courses-details.js and si.js through Node.js,
so the document always matches what the website shows.

Usage:  python3 tools/build_curriculum_doc.py      (requires node)
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ["assets/data/content.js", "assets/data/courses-details.js", "assets/data/si.js"]

js = "global.window = {};" + "".join((ROOT / f).read_text(encoding="utf-8") for f in FILES) + \
     ";process.stdout.write(JSON.stringify(window.DD_CONTENT))"
D = json.loads(subprocess.run(["node", "-e", js], capture_output=True, text=True, check=True).stdout)

L = {l["id"]: l for l in D["levels"]}
T = {t["id"]: t for t in D["tracks"]}
MODES = {k: v["name"]["en"] for k, v in D["modes"].items()}


def hours(c):
    return f'{c["hours"]} h' if isinstance(c["hours"], int) else c["hours"]["en"]


out = ["# DeepDistrict curriculum / หลักสูตร DeepDistrict", "",
       "_Generated by `tools/build_curriculum_doc.py` from the site data. Edit the data files, then re-run._", "",
       "Every course is personalised (pace, schedule, group size, language and project topic) and offered",
       "live on Zoom, onsite in Bangkok and/or hybrid as listed. Hours are indicative.", "",
       "## Learning levels / ระดับการเรียนรู้", ""]
for l in D["levels"]:
    out += [f'- **{l["id"]}. {l["short"]["en"]} / {l["short"]["th"]}**: {l["text"]["en"]}']
out += ["", "## Course overview / ภาพรวมรายวิชา", "",
        "| Code | Course | รายวิชา | Track | Level | Hours | Modes |", "|---|---|---|---|---|---|---|"]
for c in D["courses"]:
    d = D["details"].get(c["code"], {})
    lvl = "All levels" if c.get("anyLevel") else L[c["level"]]["short"]["en"]
    out.append(f'| {c["code"]} | {c["title"]["en"]} | {c["title"]["th"]} | {T[c["track"]]["name"]["en"]} | {lvl} | {hours(c)} | {", ".join(MODES[m] for m in d.get("modes", []))} |')
out += ["", "## Course details / รายละเอียดรายวิชา", ""]
for c in D["courses"]:
    d = D["details"].get(c["code"], {})
    out += [f'### {c["code"]} · {c["title"]["en"]}', f'_{c["title"]["th"]}_', "",
            c["text"]["en"], "", c["text"]["th"], "",
            f'- **Prerequisite / พื้นฐาน:** {d["prereq"]["en"]} / {d["prereq"]["th"]}',
            f'- **Final project / โปรเจกต์:** {d["project"]["en"]} / {d["project"]["th"]}',
            f'- **Tools:** {", ".join(c["tools"])}', "", "**Modules / บทเรียน**", ""]
    out += [f'{i}. {m["en"]} / {m["th"]}' for i, m in enumerate(d["modules"], 1)]
    out += ["", "**Outcomes / ผลลัพธ์**", ""] + [f'- {o["en"]} / {o["th"]}' for o in d["outcomes"]] + [""]
out += ["## Domain learning paths / เส้นทางเฉพาะสาขา", ""]
for dm in D["domains"]:
    out += [f'- **{dm["name"]["en"]} / {dm["name"]["th"]}**: ' + " → ".join(dm["path"])]
out += ["", "## Research pathway / เส้นทางการทำวิจัย", ""]
out += [f'{i}. **{s["name"]["en"]} / {s["name"]["th"]}**: {s["text"]["en"]}' for i, s in enumerate(D["researchSteps"], 1)]
(ROOT / "docs" / "CURRICULUM.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f'docs/CURRICULUM.md written: {len(D["courses"])} courses')
